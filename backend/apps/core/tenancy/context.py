"""Python-side tenant context (Phase 3 plan §8.1; ADR-042).

The current tenant lives in a :class:`contextvars.ContextVar`, which is local to each thread
and each asyncio task, so concurrent requests and tasks never see each other's tenant.

A bound context alone grants **nothing**: the database only sees a tenant once
:func:`apps.core.tenancy.transaction.tenant_atomic` has applied it to the current transaction,
and the query guard rejects every query issued while a context is bound but not applied
(``TenantContextNotApplied``).
"""

from __future__ import annotations

import re
import uuid
from collections.abc import Iterator
from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass
from typing import Protocol

from apps.core.tenancy.exceptions import (
    InvalidTenantId,
    TenantContextConflict,
    TenantContextMissing,
)

# Canonical lower-case, hyphenated form only: no braces, no urn: prefix, no upper case.
_CANONICAL = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")


def validate_tenant_id(value: object) -> uuid.UUID:
    """Return ``value`` as a tenant UUID or raise :class:`InvalidTenantId`.

    Strict by design: tenant ids are primary keys generated by ``core.ids.new_id`` (UUIDv7,
    ADR-012), so anything else (nil/max UUID, other versions, non-RFC variants, loose string
    forms) is rejected instead of being coerced.
    """
    if isinstance(value, uuid.UUID):
        parsed = value
    elif isinstance(value, str):
        if not _CANONICAL.match(value):
            raise InvalidTenantId("Tenant id must be a canonical lower-case UUID string.")
        parsed = uuid.UUID(value)
    else:
        raise InvalidTenantId(f"Tenant id must be a UUID, not {type(value).__name__}.")
    if parsed.variant != uuid.RFC_4122 or parsed.version != 7:
        raise InvalidTenantId("Tenant id must be an RFC 9562 UUIDv7.")
    return parsed


@dataclass(frozen=True, slots=True)
class TenantContext:
    """The tenant a unit of work runs for. Immutable; compared by id."""

    id: uuid.UUID
    slug: str = ""
    status: str = ""

    def __post_init__(self) -> None:
        object.__setattr__(self, "id", validate_tenant_id(self.id))

    @classmethod
    def coerce(cls, value: TenantContext | uuid.UUID | str) -> TenantContext:
        if isinstance(value, TenantContext):
            return value
        return cls(id=validate_tenant_id(value))


_CURRENT: ContextVar[TenantContext | None] = ContextVar("erp_tenant_context", default=None)


class ActivePlatformOperation(Protocol):
    """What ``tenant_atomic`` needs to know about an enclosing ``platform_scope``."""

    operation_id: str

    def allows_tenant_transactions(self) -> bool: ...

    def touch(self, tenant_id: uuid.UUID) -> None: ...


# Set only by ``apps.core.tenancy.platform.platform_scope``; kept here to avoid an import cycle.
_PLATFORM_OPERATION: ContextVar[ActivePlatformOperation | None] = ContextVar(
    "erp_platform_operation", default=None
)


def active_platform_operation() -> ActivePlatformOperation | None:
    return _PLATFORM_OPERATION.get()


def current_tenant() -> TenantContext | None:
    """The bound tenant context, or ``None`` (platform / no tenant)."""
    return _CURRENT.get()


def require_tenant() -> TenantContext:
    """The bound tenant context; raises :class:`TenantContextMissing` when there is none."""
    ctx = _CURRENT.get()
    if ctx is None:
        raise TenantContextMissing("No tenant context is bound (fail closed).")
    return ctx


@contextmanager
def bind_tenant(tenant: TenantContext | uuid.UUID | str) -> Iterator[TenantContext]:
    """Bind ``tenant`` in Python only (no database effect) and always restore on exit.

    Used by boundaries that establish a tenant before opening its transaction (request
    middleware in M3, ``TenantTask`` in M7). Rebinding a *different* tenant raises
    :class:`TenantContextConflict`; rebinding the same tenant is a no-op.
    """
    ctx = TenantContext.coerce(tenant)
    active = _CURRENT.get()
    if active is not None and active.id != ctx.id:
        raise TenantContextConflict("A different tenant context is already bound.")
    token = _CURRENT.set(ctx)
    try:
        yield ctx
    finally:
        _CURRENT.reset(token)


def _reset_for_boundary() -> TenantContext | None:
    """Clear any bound context (leak detectors only). Returns what was bound."""
    leaked = _CURRENT.get()
    if leaked is not None:
        _CURRENT.set(None)
    return leaked
